<script>
// Email Copy Functionality
function copyEmail(event) {
  const email = 'contact@phelonpreneurnetwork.com';
  const tooltip = document.getElementById('copyTooltip');
  
  navigator.clipboard.writeText(email).then(() => {
    tooltip.textContent = 'Copied!';
    tooltip.classList.add('show');
    
    setTimeout(() => {
      tooltip.classList.remove('show');
      setTimeout(() => {
        tooltip.textContent = 'Click to copy';
      }, 300);
    }, 2000);
  }).catch(err => {
    tooltip.textContent = 'Failed to copy';
    tooltip.classList.add('show');
    setTimeout(() => {
      tooltip.classList.remove('show');
    }, 2000);
  });
}

// Hover effect for email display
const emailDisplay = document.querySelector('.email-display');
const tooltip = document.getElementById('copyTooltip');

emailDisplay.addEventListener('mouseenter', () => {
  if (!tooltip.classList.contains('show') || tooltip.textContent === 'Click to copy') {
    tooltip.style.opacity = '0.8';
    tooltip.style.transform = 'translateX(-50%) scale(1)';
  }
});

emailDisplay.addEventListener('mouseleave', () => {
  if (!tooltip.classList.contains('show')) {
    tooltip.style.opacity = '0';
    tooltip.style.transform = 'translateX(-50%) scale(0)';
  }
});

// Scroll-triggered animations
const observerOptions = {
  threshold: 0.1,
  rootMargin: '0px 0px -50px 0px'
};

const observer = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      entry.target.style.opacity = '1';
    }
  });
}, observerOptions);

// Observe all animate-on-scroll elements
document.addEventListener('DOMContentLoaded', () => {
  const animatedElements = document.querySelectorAll('.animate-on-scroll');
  animatedElements.forEach(el => observer.observe(el));
  
  // Add staggered animation to expectation items
  const expectationItems = document.querySelectorAll('.expectation-item');
  expectationItems.forEach((item, index) => {
    setTimeout(() => {
      item.style.opacity = '1';
      item.style.transform = 'translateX(0)';
    }, index * 150);
  });
});

// Add smooth scroll behavior
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
  anchor.addEventListener('click', function (e) {
    e.preventDefault();
    const target = document.querySelector(this.getAttribute('href'));
    if (target) {
      target.scrollIntoView({
        behavior: 'smooth',
        block: 'start'
      });
    }
  });
});

// Parallax effect on scroll (subtle)
let ticking = false;

window.addEventListener('scroll', () => {
  if (!ticking) {
    window.requestAnimationFrame(() => {
      const scrolled = window.pageYOffset;
      const parallaxElements = document.querySelectorAll('.contact-card');
      
      parallaxElements.forEach((el, index) => {
        const speed = 0.5 + (index * 0.1);
        const yPos = -(scrolled * speed / 100);
        el.style.transform = `translateY(${yPos}px)`;
      });
      
      ticking = false;
    });
    ticking = true;
  }
});
</script>

